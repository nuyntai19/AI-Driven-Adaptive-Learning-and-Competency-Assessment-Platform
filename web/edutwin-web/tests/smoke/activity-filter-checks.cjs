const assert = require('node:assert/strict');
module.exports = async ({evaluate, waitFor}) => {
  const choices = () => evaluate("Array.from(document.querySelectorAll('select')[1].options).map(o => o.value)");
  const select = (index, value) => evaluate(`(() => { const e=document.querySelectorAll('select')[${index}]; e.value=${JSON.stringify(value)}; e.dispatchEvent(new Event('change',{bubbles:true})); })()`);
  const ready = () => waitFor("document.querySelectorAll('select').length === 2 && !document.querySelectorAll('select')[1].disabled && !document.querySelector('header button').disabled");
  const refresh = () => evaluate("document.querySelector('header button').click()");
  const clear = () => evaluate("Array.from(document.querySelectorAll('button')).find(b=>b.textContent === 'Xóa bộ lọc').click()");
  await ready();
  const teacher = await choices();
  for (const action of ['AssignmentResultApproved','AttemptSubmitted','Approved','CurriculumApplied','AssignmentPublished']) assert.ok(teacher.includes(action));
  for (const action of ['TeacherPasswordReset','ClassUpdated','CenterCreated','PlatformAdminPasswordChanged']) assert.ok(!teacher.includes(action));
  assert.equal(await evaluate("document.querySelector('ol').textContent.includes('Duyệt điểm một câu')"), false);
  await select(1, 'Approved');
  await waitFor("document.querySelectorAll('ol li').length === 1 && document.querySelector('ol').textContent.includes('Duyệt điểm một câu')");
  await select(0, 'TeacherReview');
  await ready();
  assert.deepEqual(await choices(), ['', 'Approved']);
  assert.equal(await evaluate("document.querySelectorAll('select')[1].value"), 'Approved');
  await select(0, 'Assessment');
  await ready();
  assert.deepEqual(await choices(), ['', 'AttemptSubmitted']);
  assert.equal(await evaluate("document.querySelectorAll('select')[1].value"), '');
  await select(1, 'AttemptSubmitted');
  await evaluate(`document.querySelectorAll('input[type=date]').forEach(e=>{
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(e,'2026-11-18');
    e.dispatchEvent(new Event('change',{bubbles:true}));
  })`);
  await waitFor("!!window.__verification.requests.filter(r=>r.url==='/activity').at(-1).params.until");
  const filtered = await evaluate("window.__verification.requests.filter(r=>r.url==='/activity').at(-1).params");
  assert.equal(filtered.source, 'Assessment'); assert.equal(filtered.action, 'AttemptSubmitted'); assert.ok(filtered.from);
  await clear(); await ready();
  await evaluate("Array.from(document.querySelectorAll('footer button')).find(b=>b.textContent.includes('Sau')).click()");
  await waitFor("document.querySelector('footer').textContent.includes('Trang 2/')");
  await select(1, 'Approved');
  await waitFor("document.querySelector('footer').textContent.includes('Trang 1/1')");
  console.log('PASS: teacher sees scoped actions beyond the current page; source/action/date filters combine, incompatible actions clear, and filtering resets pagination.');

  // Same identity but different account type must discard the prior query cache and selected filters.
  await evaluate("window.__verification.setRole('CenterManager')");
  await ready();
  await waitFor("window.__verification.requests.filter(r=>r.url==='/activity/filter-options').at(-1).role === 'CenterManager'");
  const manager = await choices();
  for (const action of ['ClassUpdated','TeacherPasswordReset','AssignmentCreated','CurriculumApplied']) assert.ok(manager.includes(action));
  for (const action of ['AssignmentResultApproved','AttemptSubmitted','Approved','CenterCreated','PlatformAdminPasswordChanged']) assert.ok(!manager.includes(action));
  assert.equal(await evaluate("document.querySelectorAll('select')[1].value"), '');
  await select(0, 'Business');
  assert.deepEqual(await choices(), ['', 'AssignmentCreated']);
  await select(1, 'AssignmentCreated');
  await waitFor("document.querySelectorAll('ol li').length === 1 && document.querySelector('ol').textContent.includes('Tạo bài tập')");
  await select(0, 'Audit'); await ready();
  assert.deepEqual(await choices(), ['', 'ClassUpdated', 'TeacherPasswordReset']);
  assert.equal(await evaluate("document.querySelectorAll('select')[1].value"), '');
  await select(1, 'ClassUpdated'); await select(0, ''); await ready();
  assert.equal(await evaluate("document.querySelectorAll('select')[1].value"), 'ClassUpdated');
  await clear(); await ready();
  await evaluate(`(() => {const r=window.__verification; r.options.CenterManager.push({source:'Audit',action:'ClassArchived'}); r.rows.CenterManager.push(r.row('Audit','ClassArchived',99)); r.start=r.requests.length;})()`);
  await refresh(); await ready();
  assert.ok((await choices()).includes('ClassArchived'));
  const refreshed = await evaluate("window.__verification.requests.slice(window.__verification.start).map(r=>r.url)");
  assert.ok(refreshed.includes('/activity')); assert.ok(refreshed.includes('/activity/filter-options'));
  await select(1, 'ClassArchived');
  await waitFor("document.querySelectorAll('ol li').length === 1 && document.querySelector('ol').textContent.includes('Lưu trữ lớp học')");
  await evaluate("window.__verification.failOptions=true"); await refresh();
  await waitFor("document.body.textContent.includes('Chưa tải được danh sách loại hoạt động.') && document.querySelectorAll('select')[1].disabled && !document.querySelector('header button').disabled");
  await evaluate("window.__verification.failOptions=false"); await refresh(); await ready();
  assert.equal(await evaluate("document.body.textContent.includes('Chưa tải được danh sách loại hoạt động.')"), false);
  await evaluate("window.__verification.options.CenterManager=[]; window.__verification.rows.CenterManager=[]; window.__verification.setRole('CenterManager',2)");
  await ready();
  await waitFor("document.body.textContent.includes('Chưa có hoạt động phù hợp')");
  assert.deepEqual(await choices(), ['']);
  assert.equal(await evaluate("window.__verification.requests.every(r=>r.method==='get')"), true);
  console.log('PASS: manager options exclude grading/platform actions; role changes, metadata-only events, refresh, failure recovery, and empty histories remain scoped without writes.');
};
